/**
 * Helper to find a digital twin by barcode or productId
 */
export function findDigitalTwinByBarcode(barcodeOrId: string): ComplianceDigitalTwin | undefined {
  if (!barcodeOrId) return undefined;
  const clean = barcodeOrId.trim();
  return mockComplianceDigitalTwins.find(
    (dt) => dt.barcode === clean || dt.id === clean || dt.productId === clean
  );
}

